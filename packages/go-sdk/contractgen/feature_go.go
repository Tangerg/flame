package contractgen

import (
	"encoding/json/jsontext"
	json "encoding/json/v2"
	"fmt"
	"go/format"
	"go/token"
	"maps"
	"slices"
	"strconv"
	"strings"
	"unicode"
)

type GoOptions struct{ Package, Prefix string }

type featureGo struct {
	names    map[string]string
	usesTime bool
}

// Go types are projections of the same admitted schemas as TS. Constraints stay
// in the canonical descriptor; callers validate it before decoding typed output.
func (f *Feature) Go(output GoOptions) ([]byte, error) {
	if !token.IsIdentifier(output.Package) || (output.Prefix != "" && (!token.IsIdentifier(output.Prefix) || !unicode.IsUpper([]rune(output.Prefix)[0]))) {
		return nil, fmt.Errorf("feature Go package and optional exported prefix must be identifiers")
	}
	emitter := featureGo{names: map[string]string{}}
	for name := range f.definitions {
		emitter.names[name] = output.Prefix + name
	}
	var body strings.Builder
	for _, name := range slices.Sorted(maps.Keys(f.definitions)) {
		value, err := emitter.typ(f.definitions[name])
		if err != nil {
			return nil, fmt.Errorf("feature Go %s: %w", name, err)
		}
		fmt.Fprintf(&body, "type %s %s\n\n", emitter.names[name], value)
	}
	prefix := output.Prefix
	descriptor, err := json.Marshal(f.capability.Descriptor(), json.Deterministic(true))
	if err != nil {
		return nil, err
	}
	fmt.Fprintf(&body, "const %sCapabilityJSON = %s\n\n", prefix, strconv.Quote(string(descriptor)))
	seen := map[string]bool{}
	for _, method := range f.methods {
		name := method.Name[strings.LastIndex(method.Name, "/")+1:]
		name = goFeatureIdentifier(name)
		if seen[name] {
			return nil, fmt.Errorf("feature Go operation name collision: %s", method.Name)
		}
		seen[name] = true
		fmt.Fprintf(&body, "const %s%sMethod = %s\n", prefix, name, strconv.Quote(method.Name))
		for _, value := range []struct{ suffix, path string }{{"Input", method.Input}, {"Output", method.Output}} {
			source := strings.TrimPrefix(value.path, "schema.json"+RefPrefix)
			fmt.Fprintf(&body, "type %s%s%s %s\n", output.Prefix, name, value.suffix, emitter.names[source])
		}
		if method.Stream != "" {
			source := strings.TrimPrefix(method.Stream, "schema.json"+RefPrefix)
			fmt.Fprintf(&body, "type %s%sChunk %s\n", output.Prefix, name, emitter.names[source])
		}
		body.WriteString("\n")
	}
	var result strings.Builder
	fmt.Fprintf(&result, "// Code generated by Flame contractgen from the published capability descriptor. DO NOT EDIT.\npackage %s\n\n", output.Package)
	if emitter.usesTime {
		result.WriteString("import \"time\"\n\n")
	}
	result.WriteString(body.String())
	return format.Source([]byte(result.String()))
}

func goFeatureIdentifier(value string) string {
	var out strings.Builder
	upper := true
	for _, r := range value {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			upper = true
			continue
		}
		if upper {
			r = unicode.ToUpper(r)
			upper = false
		}
		out.WriteRune(r)
	}
	name := out.String()
	if !token.IsIdentifier(name) {
		return "Field" + featureTypeName(value)
	}
	return name
}

func (e *featureGo) typ(raw jsontext.Value) (string, error) {
	var fields map[string]jsontext.Value
	if err := json.Unmarshal(raw, &fields); err != nil {
		return "", err
	}
	if ref := fields["$ref"]; len(ref) != 0 {
		var value string
		if err := json.Unmarshal(ref, &value); err != nil {
			return "", err
		}
		name := e.names[strings.TrimPrefix(value, RefPrefix)]
		if name == "" {
			return "", fmt.Errorf("unsupported reference %s", value)
		}
		return name, nil
	}
	var kind string
	if err := json.Unmarshal(fields["type"], &kind); err != nil {
		return "", fmt.Errorf("unsupported Go schema type: %s", fields["type"])
	}
	switch kind {
	case "boolean":
		return "bool", nil
	case "integer":
		if featureUnsigned(fields) {
			return "uint64", nil
		}
		return "int64", nil
	case "number":
		return "float64", nil
	case "string":
		if string(fields["format"]) == `"date-time"` {
			e.usesTime = true
			return "time.Time", nil
		}
		return "string", nil
	case "array":
		value, err := e.typ(fields["items"])
		return "[]" + value, err
	case "object":
		if additional := fields["additionalProperties"]; len(additional) != 0 && string(additional) != "false" {
			value, err := e.typ(additional)
			return "map[string]" + value, err
		}
		var properties map[string]jsontext.Value
		if len(fields["properties"]) != 0 {
			if err := json.Unmarshal(fields["properties"], &properties); err != nil {
				return "", err
			}
		}
		var required []string
		if len(fields["required"]) != 0 {
			if err := json.Unmarshal(fields["required"], &required); err != nil {
				return "", err
			}
		}
		var out strings.Builder
		out.WriteString("struct {\n")
		names := map[string]bool{}
		for _, name := range slices.Sorted(maps.Keys(properties)) {
			field := goFeatureIdentifier(name)
			if names[field] {
				return "", fmt.Errorf("Go field name collision: %s", name)
			}
			names[field] = true
			value, err := e.typ(properties[name])
			if err != nil {
				return "", err
			}
			tag := name
			if !slices.Contains(required, name) {
				value = "*" + value
				tag += ",omitzero"
			}
			fmt.Fprintf(&out, "%s %s `json:%s`\n", field, value, strconv.Quote(tag))
		}
		out.WriteString("}")
		return out.String(), nil
	default:
		return "", fmt.Errorf("unsupported Go schema type %q", kind)
	}
}

func featureUnsigned(fields map[string]jsontext.Value) bool {
	if _, err := strconv.ParseUint(string(fields["minimum"]), 10, 64); err == nil {
		return true
	}
	var bounds []map[string]jsontext.Value
	if json.Unmarshal(fields["allOf"], &bounds) != nil {
		return false
	}
	for _, bound := range bounds {
		if _, err := strconv.ParseUint(string(bound["minimum"]), 10, 64); err == nil {
			return true
		}
	}
	return false
}
