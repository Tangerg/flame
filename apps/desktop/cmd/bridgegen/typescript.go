package main

import (
	json "encoding/json/v2"
	"fmt"
	"maps"
	"slices"
	"strconv"
	"strings"

	"github.com/Tangerg/flame/qimu/contractgen"
)

const notificationAuthorization = "NotificationAuthorization"

func render(contract *contract) ([]byte, []byte, error) {
	types := contractgen.NewTypeScript(contract.definitions)
	authorization := contract.definitions[notificationAuthorization]
	if authorization == nil || len(authorization.Enum) == 0 {
		return nil, nil, fmt.Errorf("notification authorization must retain its typed enum")
	}
	var neutral strings.Builder
	neutral.WriteString("// Code generated by bridgegen from the native bridge. DO NOT EDIT.\n\n")
	neutral.WriteString("export const NotificationAuthorizationValues = [\n")
	for _, value := range authorization.Enum {
		fmt.Fprintf(&neutral, "  %s,\n", strconv.Quote(value))
	}
	neutral.WriteString("] as const;\n\nexport type NotificationAuthorization = (typeof NotificationAuthorizationValues)[number];\n")
	var out strings.Builder
	out.WriteString("// Code generated by bridgegen from actual DesktopHost methods. DO NOT EDIT.\n\n")
	out.WriteString("import { z } from \"zod\";\n")
	out.WriteString("import {\n  NotificationAuthorizationValues,\n  type NotificationAuthorization,\n} from \"@/foundation/notificationAuthorization\";\n\n")
	for _, name := range slices.Sorted(maps.Keys(contract.definitions)) {
		if name != notificationAuthorization {
			out.WriteString(strings.TrimPrefix(types.Definition(name, contract.definitions[name]), "export "))
		}
	}
	for _, name := range slices.Sorted(maps.Keys(contract.definitions)) {
		expression, err := zod(contract.definitions[name], contract.definitions)
		if err != nil {
			return nil, nil, fmt.Errorf("%s: %w", name, err)
		}
		if name == notificationAuthorization {
			expression = "z.enum(\n  NotificationAuthorizationValues,\n)"
		}
		export := ""
		for _, event := range contract.events {
			if event.payload == name {
				export = "export "
			}
		}
		fmt.Fprintf(&out, "%sconst %sSchema: z.ZodType<%s> = %s;\n\n", export, name, name, expression)
	}
	for _, event := range contract.events {
		fmt.Fprintf(&out, "export const %s = %s;\n", event.name, strconv.Quote(event.value))
	}
	out.WriteString("\ninterface DesktopHostMethods {\n")
	for _, method := range contract.methods {
		arguments := make([]string, 0, len(method.params))
		for _, parameter := range method.params {
			arguments = append(arguments, contractgen.PropertyKey(parameter.name)+": "+types.TypeOf(parameter.shape))
		}
		result := "void"
		if method.result != nil {
			result = types.TypeOf(method.result)
		}
		fmt.Fprintf(&out, "  %s: { args: [%s]; result: %s };\n", method.name, strings.Join(arguments, ", "), result)
	}
	out.WriteString("}\n\nexport const DesktopMethods = {\n")
	for _, method := range contract.methods {
		arguments := make([]string, 0, len(method.params))
		for _, parameter := range method.params {
			expression, err := zod(parameter.shape, contract.definitions)
			if err != nil {
				return nil, nil, fmt.Errorf("%s parameter %s: %w", method.name, parameter.name, err)
			}
			arguments = append(arguments, expression)
		}
		result := "z.void()"
		if method.result != nil {
			var err error
			result, err = zod(method.result, contract.definitions)
			if err != nil {
				return nil, nil, fmt.Errorf("%s result: %w", method.name, err)
			}
		}
		fmt.Fprintf(&out, "  %s: {\n    name: %s,\n    args: z.tuple([%s]),\n    result: %s,\n  },\n", method.name, strconv.Quote(method.fqn), strings.Join(arguments, ", "), result)
	}
	out.WriteString("} as const;\n\n")
	out.WriteString(`export function callDesktop<M extends keyof DesktopHostMethods>(
  binding: { call(method: string, ...args: unknown[]): Promise<unknown> },
  method: M,
  ...args: DesktopHostMethods[M]["args"]
): Promise<unknown> {
  const contract = DesktopMethods[method];
  return binding.call(contract.name, ...contract.args.parse(args));
}
`)
	return []byte(out.String()), []byte(neutral.String()), nil
}

// The native bridge uses a deliberately small JSON subset. A new keyword must
// get an actual client projection before generation can accept it.
func zod(node *contractgen.Schema, definitions contractgen.Definitions) (string, error) {
	if node == nil || node.TypeScriptType != "" {
		return "", fmt.Errorf("missing or opaque wire schema")
	}
	body, err := json.Marshal(node)
	if err != nil {
		return "", err
	}
	var keywords map[string]any
	if err := json.Unmarshal(body, &keywords); err != nil {
		return "", err
	}
	for keyword := range keywords {
		switch keyword {
		case "$ref", "type", "enum", "format", "minLength", "minimum", "properties", "required":
		default:
			return "", fmt.Errorf("unsupported Zod keyword %s", keyword)
		}
	}
	if node.Ref != "" {
		name, valid := strings.CutPrefix(node.Ref, contractgen.RefPrefix)
		if !valid || definitions[name] == nil || len(keywords) != 1 {
			return "", fmt.Errorf("unresolved or refined reference %q", node.Ref)
		}
		return "z.lazy(() => " + name + "Schema)", nil
	}
	var result string
	switch node.Type {
	case contractgen.SchemaTypeString:
		if node.Minimum != nil {
			return "", fmt.Errorf("number refinement on a string")
		}
		result = "z.string()"
		if len(node.Enum) > 0 {
			result = "z.enum([" + strings.Join(contractgen.QuoteAll(node.Enum), ", ") + "])"
			if node.Format != "" || node.MinLength != nil {
				return "", fmt.Errorf("refined string enum is unsupported")
			}
		}
		if node.Format != "" {
			if node.Format != "url" {
				return "", fmt.Errorf("unsupported string format %q", node.Format)
			}
			result = "z.url()"
		}
		if node.MinLength != nil {
			result += fmt.Sprintf(".min(%d)", *node.MinLength)
		}
	case contractgen.SchemaTypeNumber:
		if len(node.Enum) != 0 || node.MinLength != nil || node.Format != "" {
			return "", fmt.Errorf("string refinement on a number")
		}
		result = "z.number()"
		if node.Minimum != nil {
			result += fmt.Sprintf(".min(%d)", *node.Minimum)
		}
	case contractgen.SchemaTypeBoolean:
		if len(keywords) != 1 {
			return "", fmt.Errorf("refined boolean is unsupported")
		}
		result = "z.boolean()"
	case contractgen.SchemaTypeObject:
		if node.Format != "" || node.MinLength != nil || node.Minimum != nil || len(node.Enum) != 0 {
			return "", fmt.Errorf("scalar refinement on an object")
		}
		var fields []string
		for _, name := range slices.Sorted(maps.Keys(node.Properties)) {
			child, ok := node.Properties[name].(*contractgen.Schema)
			if !ok {
				return "", fmt.Errorf("unsupported property schema %s", name)
			}
			expression, err := zod(child, definitions)
			if err != nil {
				return "", err
			}
			if !slices.Contains(node.Required, name) {
				expression += ".optional()"
			}
			fields = append(fields, "  "+contractgen.PropertyKey(name)+": "+expression+",")
		}
		for _, name := range node.Required {
			if _, exists := node.Properties[name]; !exists {
				return "", fmt.Errorf("required field %s is absent", name)
			}
		}
		result = "z.object({\n" + strings.Join(fields, "\n") + "\n})"
	default:
		return "", fmt.Errorf("unsupported Zod type %q", node.Type)
	}
	return result, nil
}
