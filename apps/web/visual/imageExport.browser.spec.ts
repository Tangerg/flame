import { readFile } from "node:fs/promises";
import { expect, test } from "./test";
import { IMAGE_EXPORT_FIXTURES } from "./imageExportFixtures";

test("downloads the actual SVG artifact as a safe PNG", async ({ page }) => {
  await page.goto("/visual/?fixture=agent&theme=light&state=long-content&locale=en");
  await page.locator("html[data-visual-ready]").waitFor();
  const preview = page.getByRole("img", { name: "Image generated by the assistant", exact: true });
  await preview.evaluate((image: HTMLImageElement) => image.decode());
  await preview.click();
  const dialog = page.getByRole("dialog", { name: "Image generated by the assistant" });
  const downloaded = page.waitForEvent("download", { timeout: 5000 });
  await dialog.getByRole("button", { name: "Download PNG", exact: true }).click();
  const download = await downloaded;
  expect(download.suggestedFilename()).toBe("flame-image.png");
  expect(await download.failure()).toBeNull();
  const material = await readFile((await download.path())!);
  expect([...material.subarray(0, 8)]).toEqual([137, 80, 78, 71, 13, 10, 26, 10]);
  expect(material.readUInt32BE(16)).toBe(240);
});

test("all preview formats and inline encodings produce PNG for the native file boundary", async ({
  page,
}) => {
  await page.goto("/visual/?fixture=agent&state=idle&locale=en");
  await page.locator("html[data-visual-ready]").waitFor();
  const external: string[] = [];
  page.on("request", (request) => {
    if (request.url().startsWith("https://image-export.invalid/")) external.push(request.url());
  });
  const png = IMAGE_EXPORT_FIXTURES.find((image) => image.mime === "image/png")!;
  const sources = IMAGE_EXPORT_FIXTURES.map((image) => `data:${image.mime};base64,${image.base64}`);
  const jpeg = IMAGE_EXPORT_FIXTURES.find((image) => image.mime === "image/jpeg")!;
  sources.push(
    `data:image/jpg;base64,${jpeg.base64}`,
    `DATA:IMAGE/PNG;charset=utf-8;BASE64,${png.base64}`,
    `data:image/png,${[...Buffer.from(png.base64, "base64")].map((byte) => `%${byte.toString(16).padStart(2, "0")}`).join("")}`,
    `data:image/svg+xml;charset=utf-8,${encodeURIComponent('<svg xmlns="http://www.w3.org/2000/svg" width="2" height="3" onload="fetch(\'https://image-export.invalid/script\')"><image href="https://image-export.invalid/image.png"/><rect width="2" height="3" fill="blue"/></svg>')}`,
  );
  const results = await page.evaluate(async (sources) => {
    const exportModule = "/src/foundation/imageExport.ts";
    const hostModule = "/src/platform/desktopHost.ts";
    const bridgeModule = "/src/platform/desktop.generated.ts";
    const { createImageExport }: typeof import("@/foundation/imageExport") = await import(
      exportModule
    );
    const { createDesktopHostClient }: typeof import("@/platform/desktopHost") = await import(
      hostModule
    );
    const { DesktopMethods }: typeof import("@/platform/desktop.generated") = await import(
      bridgeModule
    );
    const captured: { name: string; prefix: number[]; width: number; height: number }[] = [];
    const host = createDesktopHostClient({
      async call(method, filename, encoded) {
        if (method !== DesktopMethods.SaveFile.name) throw new Error("unexpected native method");
        const bytes = Uint8Array.from(atob(encoded as string), (character) =>
          character.charCodeAt(0),
        );
        const image = await createImageBitmap(new Blob([bytes], { type: "image/png" }));
        captured.push({
          name: filename as string,
          prefix: [...bytes.slice(0, 8)],
          width: image.width,
          height: image.height,
        });
        image.close();
        return true;
      },
      on: async () => () => {},
    });
    const save = createImageExport("captured", host.saveFile);
    const outcomes = [];
    for (const source of sources) outcomes.push(await save(source));
    return { captured, outcomes };
  }, sources);
  expect(results.outcomes).toEqual(sources.map(() => "saved"));
  expect(results.captured).toEqual(
    sources.map(() => ({
      name: "captured.png",
      prefix: [137, 80, 78, 71, 13, 10, 26, 10],
      width: 2,
      height: 3,
    })),
  );
  expect(external).toEqual([]);
});
