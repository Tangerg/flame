import { act, fireEvent, render, screen, waitFor, within } from "@testing-library/react";
import { describe, expect, it, vi } from "vitest";
import { MESSAGE_CONTENT_CLASS } from "@/features/chat/message/ui/messageContent";
import { MarkdownRenderer } from "@/features/chat/message/ui/markdown/MarkdownRenderer";
import { SvgArtifact } from "@/features/chat/message/ui/markdown/SvgArtifact";

const SVG =
  '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 2400 1600">\n  <text x="20" y="40">Runtime · 节点图</text>\n  <script>alert("inert")</script>\n</svg>';
const LABEL = "Image generated by the assistant";
const PNG =
  "data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=";
const svgSource = (code: string) => "data:image/svg+xml;charset=utf-8," + encodeURIComponent(code);
const fence = (language: string, code = SVG) => ["```" + language, code, "```"].join("\n");

async function open(button: HTMLElement) {
  button.focus();
  await act(async () => fireEvent.click(button));
  return screen.getByRole("dialog", { name: LABEL });
}

async function close(button: HTMLElement) {
  await act(async () =>
    fireEvent.click(screen.getByRole("button", { name: "Close image preview" })),
  );
  await waitFor(() => expect(screen.queryByRole("dialog")).toBeNull());
  await waitFor(() => expect(document.activeElement).toBe(button));
}

describe("SvgArtifact", () => {
  it.each(["svg", "xml", "html", "htm"])(
    "opens a %s SVG fence as an inert image and returns to its source",
    async (language) => {
      const { container } = render(<MarkdownRenderer text={fence(language)} reveal="instant" />);
      const source = screen.getByRole("button", { name: LABEL });
      const preview = source.querySelector("img");
      expect(preview?.getAttribute("src")).toBe(svgSource(SVG));
      expect(
        source.closest('[data-slot="shiki-preview-body"]')?.querySelector("svg,script"),
      ).toBeNull();
      expect(container.querySelector("pre")).toBeNull();

      const dialog = await open(source);
      expect(within(dialog).getByRole("img", { name: LABEL }).getAttribute("src")).toBe(
        svgSource(SVG),
      );
      expect(within(dialog).getByRole("button", { name: "Zoom in image" })).toBeTruthy();
      expect(dialog.querySelector("script")).toBeNull();
      await close(source);
    },
  );

  it("keeps generated SVGs in source order within their own reply and copies the complete original code", async () => {
    const writeText = vi.fn().mockResolvedValue(undefined);
    const clipboard = Object.getOwnPropertyDescriptor(navigator, "clipboard");
    Object.defineProperty(navigator, "clipboard", { configurable: true, value: { writeText } });
    try {
      render(
        <>
          <div className={MESSAGE_CONTENT_CLASS}>
            <MarkdownRenderer
              text={"![Architecture](" + PNG + ")\n\n" + fence("svg")}
              reveal="instant"
            />
          </div>
          <div className={MESSAGE_CONTENT_CLASS}>
            <MarkdownRenderer text={"![Other reply](" + PNG + ")"} reveal="instant" />
          </div>
        </>,
      );
      const source = screen.getByRole("button", { name: LABEL });
      const dialog = await open(source);
      expect(within(dialog).getByRole("status").textContent).toBe("2 / 2");
      await act(async () =>
        fireEvent.click(within(dialog).getByRole("button", { name: "Previous image" })),
      );
      expect(within(dialog).getByRole("img", { name: "Architecture" }).getAttribute("src")).toBe(
        PNG,
      );
      expect(within(dialog).getByRole("status").textContent).toBe("1 / 2");
      await act(async () =>
        fireEvent.click(within(dialog).getByRole("button", { name: "Next image" })),
      );
      expect(within(dialog).getByRole("img", { name: LABEL }).getAttribute("src")).toBe(
        svgSource(SVG),
      );
      await close(source);
      await act(async () => fireEvent.click(screen.getByRole("button", { name: "Copy code" })));
      expect(writeText).toHaveBeenCalledExactlyOnceWith(SVG);
    } finally {
      if (clipboard) Object.defineProperty(navigator, "clipboard", clipboard);
      else Reflect.deleteProperty(navigator, "clipboard");
    }
  });

  it("keeps the opening image while code updates and reads the new image when reopened", async () => {
    const view = (code: string) => (
      <div className={MESSAGE_CONTENT_CLASS}>
        <SvgArtifact code={code} lang="svg" />
      </div>
    );
    const { rerender } = render(view(SVG));
    const source = screen.getByRole("button", { name: LABEL });
    const dialog = await open(source);
    const updated = SVG.replace("Runtime", "Desktop");
    rerender(view(updated));
    expect(within(dialog).getByRole("img", { name: LABEL }).getAttribute("src")).toBe(
      svgSource(SVG),
    );
    await close(source);
    expect(source.querySelector("img")?.getAttribute("src")).toBe(svgSource(updated));
    const reopened = await open(source);
    expect(within(reopened).getByRole("img", { name: LABEL }).getAttribute("src")).toBe(
      svgSource(updated),
    );
    await close(source);
  });
});
