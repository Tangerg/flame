func writeGoBindings(local, remote string) error {
	metas := delivery.Contract().Metas()
	for _, target := range []struct {
		directory, pkg, receiver string
		remote                   bool
	}{
		{local, "runtime", "binding", false}, {remote, "client", "Client", true},
	} {
		if target.directory == "" {
			continue
		}
		var body strings.Builder
		body.WriteString("// Code generated by contractgen. DO NOT EDIT.\npackage " + target.pkg + "\nimport (\n\"context\"\n\"iter\"\n\"github.com/Tangerg/flame/packages/go-sdk/protocol\"\n")
		var signatureTypes []reflect.Type
		for _, meta := range metas {
			signatureTypes = append(signatureTypes, meta.Params, meta.Result, meta.Event)
		}
		for _, path := range goBindingImports(signatureTypes...) {
			fmt.Fprintf(&body, "%q\n", path)
		}
		if !target.remote {
			body.WriteString("\"github.com/Tangerg/flame/runtime/internal/delivery\"\n")
		}
		body.WriteString(")\n")
		for _, meta := range metas {
			if meta.GoName == "" {
				return fmt.Errorf("%s has no Go binding name", meta.Name)
			}
			request, argument := "request "+goType(meta.Params), "request"
			if meta.Params == reflect.TypeFor[struct{}]() {
				request, argument = "", "struct{}{}"
			}
			if request != "" {
				request += ", "
			}
			option := goOptions(meta)
			result := goType(meta.Result)
			name := fmt.Sprintf("%q", meta.Name.String())
			if !target.remote {
				name = "delivery.Name(" + name + ")"
			}
			fmt.Fprintf(&body, "func (r *%s) %s(ctx context.Context, %soptions protocol.%s) ", target.receiver, meta.GoName, request, option)
			switch {
			case meta.Kind == delivery.KindStream:
				event := goType(meta.Event)
				fmt.Fprintf(&body, "(%s, iter.Seq2[%s,error], error) { return r.invokeStream[%s,%s,%s](ctx,%s,%s,options.Metadata()) }\n", result, event, goType(meta.Params), result, event, name, argument)
			case meta.Result == nil:
				fmt.Fprintf(&body, "error { return r.invokeAck[%s](ctx,%s,%s,options.Metadata()) }\n", goType(meta.Params), name, argument)
			default:
				fmt.Fprintf(&body, "(%s,error) { return r.invoke[%s,%s](ctx,%s,%s,options.Metadata()) }\n", result, goType(meta.Params), result, name, argument)
			}
		}
		if err := writeGoProjection(target.directory, "operations.generated.go", body.String()); err != nil {
			return err
		}
	}
	if remote == "" {
		return nil
	}
	var body strings.Builder
	body.WriteString("// Code generated by contractgen. DO NOT EDIT.\npackage client\nimport (\n\"reflect\"\n\"github.com/Tangerg/flame/packages/go-sdk/protocol\"\n")
	var reflectedTypes []reflect.Type
	for _, meta := range metas {
		reflectedTypes = append(reflectedTypes, meta.Result, meta.Event)
	}
	for _, path := range goBindingImports(reflectedTypes...) {
		fmt.Fprintf(&body, "%q\n", path)
	}
	body.WriteString(")\nvar methodMetadata = map[string]methodMeta{\n")
	for _, meta := range metas {
		event := "nil"
		if meta.Event != nil {
			event = "reflect.TypeFor[" + goType(meta.Event) + "]()"
		}
		fmt.Fprintf(&body, "%q: {Name:%q, Kind:%sMethod, Operation:%sOperation, Result:reflect.TypeFor[%s](), Event:%s, ResultNullable:%t", meta.Name, meta.Name, meta.Kind, meta.Operation, goType(meta.Result), event, meta.ResultNullable)
		if len(meta.Acknowledgement) > 0 {
			fmt.Fprintf(&body, ", AcknowledgementMismatch: acknowledgementMismatch%s", meta.GoName)
		}
		body.WriteString("},\n")
	}
	body.WriteString("}\n")
	for _, meta := range metas {
		if len(meta.Acknowledgement) > 0 {
			writeGoAcknowledgementCheck(&body, meta)
		}
	}
	body.WriteString("var problemCodes = map[string]int{\n")
	codes := dispatch.ProblemCodes()
	for _, name := range slices.Sorted(maps.Keys(codes)) {
		fmt.Fprintf(&body, "%q:%d,\n", name, codes[name])
	}
	body.WriteString("}\nvar refusalProblems = map[string]int{\n")
	refusals := flamehttp.RefusalProblems()
	for _, name := range slices.Sorted(maps.Keys(refusals)) {
		fmt.Fprintf(&body, "%q:%d,\n", name, refusals[name])
	}
	body.WriteString("}\nconst (\n")
	httpContract := flamehttp.Contract()
	for _, endpoint := range httpContract.Endpoints {
		if endpoint.Kind == flamehttp.EndpointKindRPC {
			fmt.Fprintf(&body, "rpcPath = %q\n", endpoint.Path)
		}
	}
	fmt.Fprintf(&body, "headerIdempotencyKey = %q\nheaderIdempotencyNamespace = %q\nheaderLastEventID = %q\nheaderRequestID = %q\nheaderMethod = %q\n",
		httpContract.Headers.IdempotencyKey, httpContract.Headers.IdempotencyNamespace,
		httpContract.Headers.LastEventID, httpContract.Headers.RequestID, httpContract.Headers.Method)
	fmt.Fprintf(&body, "notificationRunEvent = %q\nnotificationRuntimeEvent = %q\nnotificationPluginStream = %q\n)\n", dispatch.NotificationRunEvent, dispatch.NotificationRuntimeEvent, dispatch.NotificationPluginStream)
	return writeGoProjection(remote, "metadata.generated.go", body.String())
}

func goType(value reflect.Type) string {
	if value == nil {
		return "struct{}"
	}
	return strings.ReplaceAll(value.String(), "github.com/Tangerg/flame/packages/go-sdk/protocol.", "protocol.")
}

func goBindingImports(values ...reflect.Type) []string {
	paths := map[string]bool{}
	var visit func(reflect.Type)
	visit = func(value reflect.Type) {
		if value == nil {
			return
		}
		if path := value.PkgPath(); path != "" {
			if path != "github.com/Tangerg/flame/packages/go-sdk/protocol" {
				paths[path] = true
			}
			return
		}
		switch value.Kind() {
		case reflect.Pointer, reflect.Slice, reflect.Array:
			visit(value.Elem())
		case reflect.Map:
			visit(value.Key())
			visit(value.Elem())
		}
	}
	for _, value := range values {
		visit(value)
	}
	return slices.Sorted(maps.Keys(paths))
}

func goOptions(meta delivery.MethodMeta) string {
	switch {
	case meta.Operation == delivery.OperationExtension:
		return "PluginCallOptions"
	case meta.Operation == delivery.OperationCommand && meta.Kind == delivery.KindStream:
		return "RunCommandOptions"
	case meta.Operation == delivery.OperationCommand:
		return "CommandOptions"
	case meta.ReplayCursor == delivery.ReplayCursorRun:
		return "RunSubscriptionOptions"
	case meta.Operation == delivery.OperationSubscription:
		return "SubscriptionOptions"
	default:
		return "CallOptions"
	}
}

func writeGoProjection(directory, name, source string) error {
	encoded, err := format.Source([]byte(source))
	if err != nil {
		return fmt.Errorf("format %s: %w", name, err)
	}
	if err := os.MkdirAll(directory, 0o755); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(directory, name), encoded, 0o644)
}
