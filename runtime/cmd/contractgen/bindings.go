package main

import (
	"fmt"
	"go/format"
	"maps"
	"os"
	"path/filepath"
	"reflect"
	"slices"
	"strings"

	"github.com/Tangerg/flame/runtime/internal/delivery"
	"github.com/Tangerg/flame/runtime/internal/delivery/dispatch"
	flamehttp "github.com/Tangerg/flame/runtime/internal/delivery/transport/http"
)

func writeGoBindings(local, remote string) error {
	metas := delivery.Contract().Metas()
	for _, target := range []struct {
		directory, pkg, receiver string
		remote                   bool
	}{
		{local, "runtime", "binding", false}, {remote, "runtimeclient", "Client", true},
	} {
		if target.directory == "" {
			continue
		}
		var body strings.Builder
		body.WriteString("// Code generated by contractgen. DO NOT EDIT.\npackage " + target.pkg + "\nimport (\n\"context\"\n\"iter\"\n\"github.com/Tangerg/flame/runtime/protocol\"\n")
		if !target.remote {
			body.WriteString("\"github.com/Tangerg/flame/runtime/internal/delivery\"\n")
		}
		body.WriteString(")\n")
		for _, meta := range metas {
			if meta.GoName == "" {
				return fmt.Errorf("%s has no Go binding name", meta.Name)
			}
			request, argument := "request "+goType(meta.Params), "request"
			if meta.Params == reflect.TypeFor[struct{}]() {
				request, argument = "", "struct{}{}"
			}
			if request != "" {
				request += ", "
			}
			option, convert := goOptions(meta)
			result := goType(meta.Result)
			name := fmt.Sprintf("%q", meta.Name.String())
			if !target.remote {
				name = "delivery.Name(" + name + ")"
			}
			fmt.Fprintf(&body, "func (r *%s) %s(ctx context.Context, %soptions protocol.%s) ", target.receiver, meta.GoName, request, option)
			switch {
			case meta.Kind == delivery.KindStream:
				event := goType(meta.Event)
				fmt.Fprintf(&body, "(%s, iter.Seq2[%s,error], error) { return r.invokeStream[%s,%s,%s](ctx,%s,%s,%s(options)) }\n", result, event, goType(meta.Params), result, event, name, argument, convert)
			case meta.Result == nil:
				fmt.Fprintf(&body, "error { return r.invokeAck[%s](ctx,%s,%s,%s(options)) }\n", goType(meta.Params), name, argument, convert)
			default:
				fmt.Fprintf(&body, "(%s,error) { return r.invoke[%s,%s](ctx,%s,%s,%s(options)) }\n", result, goType(meta.Params), result, name, argument, convert)
			}
		}
		if err := writeGoProjection(target.directory, "operations.generated.go", body.String()); err != nil {
			return err
		}
	}
	if remote == "" {
		return nil
	}
	var body strings.Builder
	body.WriteString("// Code generated by contractgen. DO NOT EDIT.\npackage runtimeclient\nimport (\n\"reflect\"\n\"github.com/Tangerg/flame/runtime/protocol\"\n)\nvar methodMetadata = map[string]methodMeta{\n")
	for _, meta := range metas {
		event := "nil"
		if meta.Event != nil {
			event = "reflect.TypeFor[" + goType(meta.Event) + "]()"
		}
		fmt.Fprintf(&body, "%q: {Name:%q, Kind:%q, Operation:%q, Result:reflect.TypeFor[%s](), Event:%s, ResultNullable:%t},\n", meta.Name, meta.Name, meta.Kind, meta.Operation, goType(meta.Result), event, meta.ResultNullable)
	}
	body.WriteString("}\nvar problemCodes = map[string]int{\n")
	codes := dispatch.ProblemCodes()
	for _, name := range slices.Sorted(maps.Keys(codes)) {
		fmt.Fprintf(&body, "%q:%d,\n", name, codes[name])
	}
	body.WriteString("}\nvar refusalProblems = map[string]int{\n")
	refusals := flamehttp.RefusalProblems()
	for _, name := range slices.Sorted(maps.Keys(refusals)) {
		fmt.Fprintf(&body, "%q:%d,\n", name, refusals[name])
	}
	body.WriteString("}\nconst (\n")
	for _, endpoint := range flamehttp.Contract().Endpoints {
		if endpoint.Kind == flamehttp.EndpointKindRPC {
			fmt.Fprintf(&body, "rpcPath = %q\n", endpoint.Path)
		}
	}
	fmt.Fprintf(&body, "notificationRunEvent = %q\nnotificationRuntimeEvent = %q\nnotificationPluginStream = %q\n)\n", dispatch.NotificationRunEvent, dispatch.NotificationRuntimeEvent, dispatch.NotificationPluginStream)
	return writeGoProjection(remote, "metadata.generated.go", body.String())
}

func goType(value reflect.Type) string {
	if value == nil {
		return "struct{}"
	}
	return strings.ReplaceAll(value.String(), "github.com/Tangerg/flame/runtime/protocol.", "protocol.")
}

func goOptions(meta delivery.MethodMeta) (string, string) {
	switch {
	case meta.Operation == delivery.OperationExtension:
		return "PluginCallOptions", "pluginCallOptions"
	case meta.Operation == delivery.OperationCommand && meta.Kind == delivery.KindStream:
		return "RunCommandOptions", "runCommandOptions"
	case meta.Operation == delivery.OperationCommand:
		return "CommandOptions", "commandOptions"
	case meta.ReplayCursor == delivery.ReplayCursorRun:
		return "RunSubscriptionOptions", "runSubscriptionOptions"
	case meta.Operation == delivery.OperationSubscription:
		return "SubscriptionOptions", "subscriptionOptions"
	default:
		return "CallOptions", "callOptions"
	}
}

func writeGoProjection(directory, name, source string) error {
	encoded, err := format.Source([]byte(source))
	if err != nil {
		return fmt.Errorf("format %s: %w", name, err)
	}
	if err := os.MkdirAll(directory, 0o755); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(directory, name), encoded, 0o644)
}
