package main

import (
	"fmt"
	"reflect"
	"strings"

	"github.com/Tangerg/flame/packages/go-sdk/extension"
	"github.com/Tangerg/flame/packages/go-sdk/protocol"
	"github.com/Tangerg/flame/qimu/contractgen"
	"github.com/Tangerg/flame/runtime/internal/adapter/toolset"
)

func newClientValues(set *schemaSet) (string, error) {
	var out strings.Builder
	out.WriteString("// Code generated by cmd/contractgen. DO NOT EDIT.\n\n")
	out.WriteString("// Shared scalar facts do not carry Runtime records or operation handles into client models.\n")
	for _, scalar := range []reflect.Type{
		reflect.TypeFor[protocol.ApprovalDecision](),
		reflect.TypeFor[protocol.ApprovalGate](),
		reflect.TypeFor[protocol.ApprovalMode](),
		reflect.TypeFor[protocol.ApprovalRuleDecision](),
		reflect.TypeFor[protocol.FileEntryType](),
		reflect.TypeFor[protocol.InterruptType](),
		reflect.TypeFor[protocol.ItemStatus](),
		reflect.TypeFor[protocol.MessagePhase](),
		reflect.TypeFor[protocol.RememberScopeKind](),
		reflect.TypeFor[extension.RendererSelectorKind](),
		reflect.TypeFor[extension.SettingsIntent](),
		reflect.TypeFor[protocol.RestoreType](),
		reflect.TypeFor[protocol.RunStatus](),
		reflect.TypeFor[protocol.SessionStatus](),
		reflect.TypeFor[protocol.ToolCategory](),
		reflect.TypeFor[protocol.WorkspaceAvailability](),
	} {
		values, err := clientScalarValues(set, scalar)
		if err != nil {
			return "", err
		}
		fmt.Fprintf(&out, "export type %s = %s;\n\n", defName(scalar), strings.Join(contractgen.QuoteAll(values), " | "))
	}
	recovery := reflect.TypeFor[protocol.RecoveryAction]()
	actions, ok := enumValues(recovery)
	if !ok {
		return "", fmt.Errorf("client scalar %s has no declared closed values", recovery)
	}
	fmt.Fprintf(&out, "export type %s = %s;\n\n", defName(recovery), strings.Join(contractgen.QuoteAll(actions), " | "))
	changes, err := clientScalarValues(set, reflect.TypeFor[toolset.ChangeStatus]())
	if err != nil {
		return "", err
	}
	fmt.Fprintf(&out, "export const CHANGE_STATUSES = [%s] as const;\n", strings.Join(contractgen.QuoteAll(changes), ", "))
	return out.String(), nil
}

func clientScalarValues(set *schemaSet, scalar reflect.Type) ([]string, error) {
	name := defName(scalar)
	node := set.defs[name]
	if set.origin[name] != scalar || node == nil || node.Type != contractgen.SchemaTypeString || len(node.Enum) == 0 {
		return nil, fmt.Errorf("client scalar %s has no closed string schema", scalar)
	}
	return node.Enum, nil
}
