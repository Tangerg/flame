package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"maps"
	"os"
	"reflect"
	"slices"
	"strconv"

	"github.com/Tangerg/flame/packages/go-sdk/filesystem"
	framebrowser "github.com/Tangerg/frame/browser"
	framehost "github.com/Tangerg/frame/host"
	framevalue "github.com/Tangerg/frame/value"
)

const jsonTagKey = "json"

func main() {
	output := flag.String("out", "../packages/go-sdk/protocol/plugin_browser.generated.go", "pure protocol output")
	flag.Parse()
	value, err := generate()
	if err == nil {
		err = os.WriteFile(*output, value, filesystem.SharedFileMode)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() ([]byte, error) {
	collected := browserTypes{}
	for _, root := range []reflect.Type{
		reflect.TypeFor[framebrowser.Authority](), reflect.TypeFor[framebrowser.Realm](),
		reflect.TypeFor[framehost.ContractRef](), reflect.TypeFor[framebrowser.UseGrant](),
	} {
		if err := collected.walk(root); err != nil {
			return nil, err
		}
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by cmd/pluginbrowsergen from Frame control types. DO NOT EDIT.\n\npackage protocol\n\n")
	for _, name := range slices.Sorted(maps.Keys(collected)) {
		writeBrowserType(&out, name, collected[name])
	}
	return format.Source(out.Bytes())
}

type browserTypes map[string]reflect.Type

func (types browserTypes) walk(value reflect.Type) error {
	switch value.Kind() {
	case reflect.Pointer, reflect.Slice:
		return types.walk(value.Elem())
	case reflect.Struct, reflect.String:
	default:
		return fmt.Errorf("unsupported browser protocol kind: %s", value)
	}
	if value.Name() == "" || value.PkgPath() == "" {
		return nil
	}
	name := browserTypeName(value)
	if previous, found := types[name]; found {
		if previous != value {
			return fmt.Errorf("browser protocol name collision: %s and %s", previous, value)
		}
		return nil
	}
	types[name] = value
	if value.Kind() != reflect.Struct || value == reflect.TypeFor[framevalue.Digest]() {
		return nil
	}
	for i := range value.NumField() {
		field := value.Field(i)
		if !projectableField(field) {
			return fmt.Errorf("browser protocol field must be explicit: %s.%s", value, field.Name)
		}
		if err := types.walk(field.Type); err != nil {
			return err
		}
	}
	return nil
}

func writeBrowserType(out *bytes.Buffer, name string, value reflect.Type) {
	if value.Kind() == reflect.String || value == reflect.TypeFor[framevalue.Digest]() {
		fmt.Fprintf(out, "type %s string\n\n", name)
		if vocabulary, ok := reflect.Zero(value).Interface().(interface{ JSONSchemaEnum() []string }); ok {
			fmt.Fprintf(out, "func (%s) Values() []string { return []string{", name)
			for _, text := range vocabulary.JSONSchemaEnum() {
				fmt.Fprintf(out, "%q,", text)
			}
			out.WriteString("} }\n\n")
		}
		return
	}
	fmt.Fprintf(out, "type %s struct {\n", name)
	for i := range value.NumField() {
		field := value.Field(i)
		if field.Anonymous {
			fmt.Fprintln(out, pureType(field.Type))
		} else {
			fmt.Fprintf(out, "%s %s %s\n", field.Name, pureType(field.Type), strconv.Quote(string(field.Tag)))
		}
	}
	out.WriteString("}\n\n")
}

func pureType(value reflect.Type) string {
	switch value.Kind() {
	case reflect.Pointer:
		return "*" + pureType(value.Elem())
	case reflect.Slice:
		return "[]" + pureType(value.Elem())
	default:
		if value.PkgPath() != "" {
			return browserTypeName(value)
		}
		return value.String()
	}
}

func projectableField(field reflect.StructField) bool {
	if !field.IsExported() {
		return false
	}
	if field.Anonymous {
		return field.Type.Kind() == reflect.Struct && field.Tag.Get(jsonTagKey) == ""
	}
	return field.Tag.Get(jsonTagKey) != ""
}

func browserTypeName(value reflect.Type) string { return "PluginBrowser" + value.Name() }
