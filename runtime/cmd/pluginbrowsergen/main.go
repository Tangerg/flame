// Command pluginbrowsergen projects Qimu's compiled control vocabulary into
// Flame's pure public protocol. It owns no independent control declarations.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"reflect"
	"slices"
	"strconv"

	"github.com/Tangerg/flame/qimu"
	"github.com/Tangerg/flame/qimu/control"
)

func main() {
	output := flag.String("out", "../packages/go-sdk/protocol/plugin_browser.generated.go", "pure protocol output")
	flag.Parse()
	value, err := generate()
	if err == nil {
		err = os.WriteFile(*output, value, 0644)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() ([]byte, error) {
	types := map[string]reflect.Type{}
	var walk func(reflect.Type) error
	walk = func(value reflect.Type) error {
		switch value.Kind() {
		case reflect.Pointer, reflect.Slice:
			return walk(value.Elem())
		case reflect.Struct, reflect.String:
		default:
			return fmt.Errorf("unsupported browser protocol kind: %s", value)
		}
		if value.Name() == "" || value.PkgPath() == "" {
			return nil
		}
		name := "PluginBrowser" + value.Name()
		if previous, found := types[name]; found {
			if previous != value {
				return fmt.Errorf("browser protocol name collision: %s and %s", previous, value)
			}
			return nil
		}
		types[name] = value
		if value.Kind() == reflect.Struct {
			for i := range value.NumField() {
				field := value.Field(i)
				if !field.IsExported() || field.Anonymous || field.Tag.Get("json") == "" {
					return fmt.Errorf("browser protocol field must be explicit: %s.%s", value, field.Name)
				}
				if err := walk(field.Type); err != nil {
					return err
				}
			}
		}
		return nil
	}
	for _, root := range []reflect.Type{
		reflect.TypeFor[control.Authority](), reflect.TypeFor[control.Realm](),
		reflect.TypeFor[qimu.ContractRef](), reflect.TypeFor[control.UseGrant](),
	} {
		if err := walk(root); err != nil {
			return nil, err
		}
	}
	var names []string
	for name := range types {
		names = append(names, name)
	}
	slices.Sort(names)
	var out bytes.Buffer
	out.WriteString("// Code generated by cmd/pluginbrowsergen from Qimu control types. DO NOT EDIT.\n\npackage protocol\n\n")
	for _, name := range names {
		value := types[name]
		if value.Kind() == reflect.String {
			fmt.Fprintf(&out, "type %s string\n\n", name)
			if vocabulary, ok := reflect.Zero(value).Interface().(interface{ Values() []string }); ok {
				fmt.Fprintf(&out, "func (%s) Values() []string { return []string{", name)
				for _, text := range vocabulary.Values() {
					fmt.Fprintf(&out, "%q,", text)
				}
				out.WriteString("} }\n\n")
			}
			continue
		}
		fmt.Fprintf(&out, "type %s struct {\n", name)
		for i := range value.NumField() {
			field := value.Field(i)
			fmt.Fprintf(&out, "%s %s %s\n", field.Name, pureType(field.Type), strconv.Quote(string(field.Tag)))
		}
		out.WriteString("}\n\n")
	}
	return format.Source(out.Bytes())
}

func pureType(value reflect.Type) string {
	switch value.Kind() {
	case reflect.Pointer:
		return "*" + pureType(value.Elem())
	case reflect.Slice:
		return "[]" + pureType(value.Elem())
	default:
		if value.PkgPath() != "" {
			return "PluginBrowser" + value.Name()
		}
		return value.String()
	}
}
