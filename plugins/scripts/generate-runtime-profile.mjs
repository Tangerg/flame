import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import { format } from "prettier";

const source = new URL(
  "../../packages/component-sdk/runtime-profile.json",
  import.meta.url,
);
const profile = JSON.parse(await readFile(source, "utf8"));
assert.match(
  profile.profile,
  /^io\.github\.tangerg\.flame\/[a-z-]+@[1-9][0-9]*$/,
);
assert.ok(
  Array.isArray(profile.modules) && Array.isArray(profile.packageExports),
);
assert.match(profile.componentExport, /^[A-Za-z_$][A-Za-z0-9_$]*$/);
assert.match(profile.moduleGraph.filename, /^[a-z][a-z0-9.-]*\.json$/);
assert.ok(Number.isSafeInteger(profile.moduleGraph.schemaVersion));
assert.ok(profile.moduleGraph.schemaVersion > 0);
const modules = new Set(profile.modules);
assert.equal(modules.size, profile.modules.length);
for (const name of profile.packageExports) {
  assert.equal(
    name,
    "@flame/ui",
    "the named package must have an explicit canonical source",
  );
  const owner = JSON.parse(
    await readFile(
      new URL("../../packages/ui/package.json", import.meta.url),
      "utf8",
    ),
  );
  assert.equal(owner.name, name);
  for (const key of Object.keys(owner.exports)) {
    assert.ok(key === "." || key.startsWith("./"));
    assert.ok(
      !key.includes("*"),
      "native host exports must name concrete modules",
    );
    if (key.endsWith(".css")) continue;
    modules.add(key === "." ? name : name + key.slice(1));
  }
}
const specifiers = [...modules].sort();
const value = {
  profile: profile.profile,
  modules: specifiers,
  moduleGraph: profile.moduleGraph,
  componentExport: profile.componentExport,
};
const ts =
  "// Code generated by generate-runtime-profile.mjs. DO NOT EDIT.\n" +
  `export const hostModuleProfile = ${JSON.stringify(value.profile)};\n` +
  `export const componentExport = ${JSON.stringify(value.componentExport)};\n` +
  `export const moduleGraph = Object.freeze(${JSON.stringify(value.moduleGraph)} as const);\n` +
  `export const hostModuleSpecifiers = Object.freeze(${JSON.stringify(specifiers, null, 2)} as const);\n`;
await writeFile(
  new URL(
    "../../packages/component-sdk/src/runtime-profile.generated.ts",
    import.meta.url,
  ),
  await format(ts, { parser: "typescript" }),
);
await writeFile(
  new URL(
    "../../packages/component-sdk/runtime-profile.generated.json",
    import.meta.url,
  ),
  JSON.stringify(value, null, 2) + "\n",
);
const goFile = new URL(
  "../../runtime/internal/adapter/integration/pluginpackage/runtime_profile.generated.go",
  import.meta.url,
);
await writeFile(
  goFile,
  "// Code generated by generate-runtime-profile.mjs. DO NOT EDIT.\npackage pluginpackage\n\n" +
    `const hostModuleProfile = ${JSON.stringify(value.profile)}\n` +
    `const moduleGraphFilename = ${JSON.stringify(value.moduleGraph.filename)}\n` +
    `const moduleGraphSchemaVersion = ${value.moduleGraph.schemaVersion}\n\n` +
    "var hostModuleSpecifiers = [...]string{\n" +
    specifiers.map((name) => "\t" + JSON.stringify(name) + ",\n").join("") +
    "}\n",
);
execFileSync("gofmt", ["-w", fileURLToPath(goFile)], { stdio: "inherit" });

const extensionFile = new URL(
  "../../packages/go-sdk/extension/component_profile.generated.go",
  import.meta.url,
);
await writeFile(
  extensionFile,
  "// Code generated by generate-runtime-profile.mjs. DO NOT EDIT.\npackage extension\n\n" +
    `const ComponentExport = ${JSON.stringify(value.componentExport)}\n`,
);
execFileSync("gofmt", ["-w", fileURLToPath(extensionFile)], {
  stdio: "inherit",
});
