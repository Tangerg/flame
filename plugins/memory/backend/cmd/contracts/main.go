package main

import (
	"bytes"
	"encoding/json/jsontext"
	json "encoding/json/v2"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"reflect"

	"github.com/Tangerg/flame/packages/go-sdk/filesystem"
	plugincontract "github.com/Tangerg/flame/packages/go-sdk/plugin/contract"
	rpc "github.com/Tangerg/flame/plugins/memory/internal/contract"
)

func main() {
	policyJSON := flag.String("caller-json", "", "published caller policy JSON output")
	policyGo := flag.String("caller-go", "", "generated Core caller policy Go output")
	flag.Parse()
	if *policyJSON != "" || *policyGo != "" {
		if err := writeCallerPolicy(*policyJSON, *policyGo); err != nil {
			log.Fatal(err)
		}
	}
	if *policyGo != "" && *policyJSON == "" {
		return
	}
	plugincontract.Publish(func() (*plugincontract.Capability, error) {
		contracts, err := rpc.NewContracts()
		return contracts.Capability, err
	})
}

func writeCallerPolicy(jsonPath, goPath string) error {
	var err error
	if jsonPath != "" {
		jsonPath, err = filepath.Abs(jsonPath)
		if err != nil {
			return err
		}
	}
	if goPath != "" {
		goPath, err = filepath.Abs(goPath)
		if err != nil {
			return err
		}
		if jsonPath == goPath {
			return errors.New("caller policy outputs must be distinct")
		}
	}
	policy := rpc.ModelCallerPolicy()
	encoded, err := json.Marshal(policy, jsontext.WithIndent("  "), json.Deterministic(true))
	if err != nil {
		return err
	}
	generated, err := callerPolicySource(policy)
	if err != nil {
		return err
	}
	for _, output := range []struct {
		path string
		data []byte
	}{{jsonPath, append(encoded, '\n')}, {goPath, generated}} {
		if output.path == "" {
			continue
		}
		if err := os.MkdirAll(filepath.Dir(output.path), filesystem.SharedDirectoryMode); err != nil {
			return err
		}
		if err := os.WriteFile(output.path, output.data, filesystem.SharedFileMode); err != nil {
			return err
		}
	}
	return nil
}

func callerPolicySource(policy any) ([]byte, error) {
	var source bytes.Buffer
	source.WriteString("// Code generated by Flame memorycontracts from the publisher's caller policy. DO NOT EDIT.\npackage memory\n\nconst (\n")
	value := reflect.ValueOf(policy)
	for i := range value.NumField() {
		field, name := value.Field(i), value.Type().Field(i).Name
		switch {
		case field.Kind() == reflect.String && field.String() != "":
			fmt.Fprintf(&source, "%s = %q\n", name, field.String())
		case field.Kind() == reflect.String:
			return nil, errors.New("caller policy tool name is required")
		case (field.Kind() == reflect.Int || field.Kind() == reflect.Int64) && field.Int() > 0:
			fmt.Fprintf(&source, "%s = %d\n", name, field.Int())
		default:
			return nil, errors.New("caller policy values must be positive integers")
		}
	}
	source.WriteString(")\n")
	return format.Source(source.Bytes())
}
