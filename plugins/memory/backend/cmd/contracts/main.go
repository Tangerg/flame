package main

import (
	"bytes"
	"encoding/json/jsontext"
	json "encoding/json/v2"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"reflect"

	rpc "github.com/Tangerg/flame/plugins/memory/backend/rpc"
)

func main() {
	policyJSON := flag.String("caller-json", "", "published caller policy JSON output")
	policyGo := flag.String("caller-go", "", "generated Core caller policy Go output")
	flag.Parse()
	if *policyJSON != "" || *policyGo != "" {
		if err := writeCallerPolicy(*policyJSON, *policyGo); err != nil {
			log.Fatal(err)
		}
	}
	if *policyGo != "" && *policyJSON == "" {
		return
	}
	contracts, err := rpc.NewContracts()
	if err != nil {
		log.Fatal(err)
	}
	data, err := json.Marshal(contracts.Capability.Descriptor())
	if err != nil {
		log.Fatal(err)
	}
	if _, err := os.Stdout.Write(data); err != nil {
		log.Fatal(err)
	}
}

func writeCallerPolicy(jsonPath, goPath string) error {
	var err error
	if jsonPath != "" {
		jsonPath, err = filepath.Abs(jsonPath)
		if err != nil {
			return err
		}
	}
	if goPath != "" {
		goPath, err = filepath.Abs(goPath)
		if err != nil {
			return err
		}
		if jsonPath == goPath {
			return errors.New("caller policy outputs must be distinct")
		}
	}
	policy := rpc.ModelCallerPolicy()
	encoded, err := json.Marshal(policy, jsontext.WithIndent("  "), json.Deterministic(true))
	if err != nil {
		return err
	}
	var source bytes.Buffer
	source.WriteString("// Code generated by Flame memorycontracts from the publisher's caller policy. DO NOT EDIT.\npackage memory\n\nconst (\n")
	value := reflect.ValueOf(policy)
	for i := range value.NumField() {
		field := value.Field(i)
		if field.Kind() != reflect.Int && field.Kind() != reflect.Int64 || field.Int() <= 0 {
			return errors.New("caller policy values must be positive integers")
		}
		fmt.Fprintf(&source, "%s = %d\n", value.Type().Field(i).Name, field.Int())
	}
	source.WriteString(")\n")
	generated, err := format.Source(source.Bytes())
	if err != nil {
		return err
	}
	for _, output := range []struct {
		path string
		data []byte
	}{{jsonPath, append(encoded, '\n')}, {goPath, generated}} {
		if output.path == "" {
			continue
		}
		if err := os.MkdirAll(filepath.Dir(output.path), 0755); err != nil {
			return err
		}
		if err := os.WriteFile(output.path, output.data, 0644); err != nil {
			return err
		}
	}
	return nil
}
