// WriteTypeScript projects compiled protocol types. It neither scans another
// checkout nor owns a second description of fields or enum values.
func WriteTypeScript(out io.Writer) error {
	var roots []reflect.Type
	for _, op := range operations {
		if op.input.Name() != "" {
			roots = append(roots, op.input)
		}
		if op.output != reflect.TypeFor[noResult]() {
			roots = append(roots, op.output)
		}
	}
	return writeTypeScript(out, true, roots...)
}

// WriteTypeScriptTypes projects consumer-owned DTO roots using the same emitter
// without adding their domain vocabulary to the framework control protocol.
func WriteTypeScriptTypes(out io.Writer, roots ...reflect.Type) error {
	return writeTypeScript(out, false, roots...)
}

func writeTypeScript(out io.Writer, includeProtocol bool, roots ...reflect.Type) error {
	types, err := collectWireTypes(roots)
	if err != nil {
		return err
	}
	names := make([]string, 0, len(types))
	for name := range types {
		names = append(names, name)
	}
	slices.Sort(names)
	var result strings.Builder
	result.WriteString("// Code generated by qimu/control. DO NOT EDIT.\n\n")
	if includeProtocol {
		fmt.Fprintf(&result, "export const PROTOCOL = %s as const;\n\n", contractgen.TypeScriptStringLiteral(Protocol))
		fmt.Fprintf(&result, "export const MAX_NAME_BYTES = %d as const;\n\n", qimu.MaxNameBytes)
	}
	for _, name := range names {
		t := types[name]
		if values, ok := reflect.Zero(t).Interface().(interface{ Values() []string }); ok {
			parts := contractgen.QuoteAll(values.Values())
			declaration := fmt.Sprintf("export type %s = %s;", name, strings.Join(parts, " | "))
			if len(declaration) > 80 {
				fmt.Fprintf(&result, "export type %s =\n  %s;\n\n", name, strings.Join(parts, " | "))
			} else {
				result.WriteString(declaration + "\n\n")
			}
			continue
		}
		if jsonvalue.TextEncoded(t) || t.Kind() != reflect.Struct {
			if t.Kind() != reflect.String && t.Kind() != reflect.Struct {
				return fmt.Errorf("control: unsupported named scalar %s", t)
			}
			fmt.Fprintf(&result, "export type %s = string;\n\n", name)
			continue
		}
		fmt.Fprintf(&result, "export interface %s {\n", name)
		for _, field := range jsonvalue.Fields(t) {
			value, err := renderWireType(field.Type)
			if err != nil {
				return err
			}
			optional := ""
			if field.Optional {
				optional = "?"
			}
			fmt.Fprintf(&result, "  readonly %s%s: %s;\n", contractgen.PropertyKey(field.Name), optional, value)
		}
		result.WriteString("}\n\n")
	}
	if includeProtocol {
		writeOperationContracts(&result, names, types)
	}
	_, err = io.WriteString(out, strings.TrimRight(result.String(), "\n")+"\n")
	return err
}

func collectWireTypes(roots []reflect.Type) (map[string]reflect.Type, error) {
	types := make(map[string]reflect.Type)
	var collect func(reflect.Type) error
	collect = func(t reflect.Type) error {
		if t.Name() != "" && (t.Kind() == reflect.Slice || t.Kind() == reflect.Array || t.Kind() == reflect.Map) {
			return fmt.Errorf("control: unsupported named collection %s", t)
		}
		if t.Kind() == reflect.Pointer || t.Kind() == reflect.Slice || t.Kind() == reflect.Array {
			return collect(t.Elem())
		}
		if t.PkgPath() == "" {
			return nil
		}
		if existing := types[t.Name()]; existing != nil {
			if existing != t {
				return fmt.Errorf("control: ambiguous generated type %s", t.Name())
			}
			return nil
		}
		types[t.Name()] = t
		if t.Kind() == reflect.Struct && !jsonvalue.TextEncoded(t) {
			for _, field := range jsonvalue.Fields(t) {
				if err := collect(field.Type); err != nil {
					return err
				}
			}
		}
		return nil
	}
	for _, root := range roots {
		if err := jsonvalue.ValidateType(root); err != nil {
			return nil, fmt.Errorf("control: invalid wire type: %w", err)
		}
		if err := collect(root); err != nil {
			return nil, err
		}
	}
	return types, nil
}

func renderWireType(t reflect.Type) (string, error) {
	if t.Kind() == reflect.Pointer {
		return renderWireType(t.Elem())
	}
	if t.Name() != "" && t.PkgPath() != "" {
		return t.Name(), nil
	}
	switch t.Kind() {
	case reflect.String:
		return "string", nil
	case reflect.Bool:
		return "boolean", nil
	case reflect.Int, reflect.Uint, reflect.Int8, reflect.Uint8, reflect.Int16, reflect.Uint16, reflect.Int32, reflect.Uint32, reflect.Int64, reflect.Uint64, reflect.Float32, reflect.Float64:
		return "number", nil
	case reflect.Slice, reflect.Array:
		value, err := renderWireType(t.Elem())
		return "readonly " + value + "[]", err
	default:
		return "", fmt.Errorf("control: unsupported protocol type %s", t)
	}
}

func fieldShape(t reflect.Type) string {
	switch t.Kind() {
	case reflect.Pointer:
		return fieldShape(t.Elem())
	case reflect.Array, reflect.Slice:
		return "[]" + fieldShape(t.Elem())
	}
	if t.Name() != "" && t.PkgPath() != "" {
		return t.Name()
	}
	return t.Kind().String()
}

func writeOperationContracts(result *strings.Builder, names []string, types map[string]reflect.Type) {
	result.WriteString("export const CONTROL_SHAPES = {\n")
	for _, name := range names {
		t := types[name]
		fmt.Fprintf(result, "  %s: ", name)
		switch values, ok := reflect.Zero(t).Interface().(interface{ Values() []string }); {
		case ok:
			fmt.Fprintf(result, "[%s]", strings.Join(contractgen.QuoteAll(values.Values()), ", "))
		case t.Kind() == reflect.Struct && !jsonvalue.TextEncoded(t):
			result.WriteString("{")
			for _, field := range jsonvalue.Fields(t) {
				shape := fieldShape(field.Type)
				if field.Optional {
					shape += "?"
				}
				fmt.Fprintf(result, "%s: %q,", contractgen.PropertyKey(field.Name), shape)
			}
			result.WriteString("}")
		default:
			result.WriteString(`"string"`)
		}
		result.WriteString(",\n")
	}
	result.WriteString("} as const;\n\nexport const CONTROL_OPERATIONS = {\n")
	for _, op := range operations {
		output := op.output.Name()
		if op.output == reflect.TypeFor[noResult]() {
			output = "null"
		}
		fmt.Fprintf(result, "  %s: { mutating: %t, output: %q },\n", op.name, op.mutating, output)
	}
	result.WriteString("} as const;\n\nexport interface ControlResults {\n")
	for _, op := range operations {
		output := op.output.Name()
		if op.output == reflect.TypeFor[noResult]() {
			output = "void"
		}
		fmt.Fprintf(result, "  %s: %s;\n", op.name, output)
	}
	result.WriteString("}\n")
}
