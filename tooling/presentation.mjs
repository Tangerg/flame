import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { rolldown } from "rolldown";
import { format, resolveConfig } from "prettier";
import { execFileSync } from "node:child_process";

const root = fileURLToPath(new URL("../", import.meta.url));
const generated = "Generated by tooling/presentation.mjs. Do not edit.";

export async function presentationFacts(repository = root) {
  const entry = join(repository, "tooling/presentation-entry.ts");
  const source = `
import { PRODUCT_NAME, PRODUCT_SLUG } from "@/app/product";
import { desktopProduct } from ${JSON.stringify(join(repository, "apps/desktop/build/product.mjs"))};
import { defaultAppearance } from "@/features/theme/kit/appearance";
import { APPEARANCE_STORAGE_KEY, THEME_PAINT_STORAGE_KEY, THEME_CLASS_PREFIX } from "@/features/theme/kit/documentTheme";
import { paletteThemeContribution } from "@/features/theme/kit/palette";
import { depthStep } from "@/features/theme/kit/tokens";
import { densityCssVariables } from "@/features/theme/kit/density";
import { uiTypeLadderCssVariables } from "@/features/theme/kit/typeLadder";
import { productIconScaleCssVariables } from "@/lib/productIconScale";
import { flameStyle } from "@/features/theme/visualStyles/flame";
import { visualStyleMotionTokens } from "@/features/theme/visualStyles/tokens";
const preference = defaultAppearance();
const palette = (scheme) => ({
  ...paletteThemeContribution({ id: scheme, label: scheme, scheme, palette: {} }, preference.accent, preference.contrast, preference).tokens,
  "depth-step": depthStep(scheme, preference.contrast),
});
const withoutPrefix = (values) => Object.fromEntries(Object.entries(values).map(([key, value]) => [key.replace(/^--/, ""), value]));
export default {
  product: { name: PRODUCT_NAME, slug: PRODUCT_SLUG, ...desktopProduct },
  light: palette("light"),
  dark: palette("dark"),
  defaults: {
    ...flameStyle.tokens,
    ...visualStyleMotionTokens(flameStyle.motion),
    ...withoutPrefix(densityCssVariables(preference.density)),
    ...withoutPrefix(uiTypeLadderCssVariables(preference.fontSize)),
    ...withoutPrefix(productIconScaleCssVariables(preference.fontSize)),
    "radius-scale": String(preference.radiusScale),
    "motion-scale": String(preference.motionScale),
  },
  preference: { visualStyle: preference.visualStyle },
  storage: { appearance: APPEARANCE_STORAGE_KEY, paint: THEME_PAINT_STORAGE_KEY },
  themeClassPrefix: THEME_CLASS_PREFIX,
};
`;
  const bundle = await rolldown({
    input: entry,
    cwd: repository,
    platform: "node",
    transform: {
      define: { "process.env.NODE_ENV": JSON.stringify("production") },
    },
    plugins: [
      {
        name: "flame-presentation-owner-source",
        resolveId(id) {
          if (id === entry) return entry;
          if (id.startsWith("@/"))
            return this.resolve(
              join(repository, "apps/web/src", id.slice(2)),
              undefined,
              { skipSelf: true },
            );
        },
        load(id) {
          if (id === entry) return source;
        },
      },
    ],
    onwarn(warning, report) {
      if (warning.code === "UNRESOLVED_IMPORT")
        throw new Error(warning.message);
      report(warning);
    },
  });
  try {
    const { output } = await bundle.generate({
      format: "esm",
      inlineDynamicImports: true,
    });
    if (output.length !== 1 || output[0].type !== "chunk")
      throw new Error("presentation owners must produce one pure module");
    const loaded = await import(
      `data:text/javascript;base64,${Buffer.from(output[0].code).toString("base64")}`
    );
    return loaded.default;
  } finally {
    await bundle.close();
  }
}

function escapeXML(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&apos;");
}

export function nativePlist(product, development) {
  const pair = (key, value) =>
    `    <key>${key}</key>\n    <string>${escapeXML(value)}</string>`;
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- ${generated} -->
<plist version="1.0">
  <dict>
${pair("CFBundleExecutable", product.slug)}
${pair("CFBundleGetInfoString", product.description)}
${pair("CFBundleIconFile", "icons")}
${pair("CFBundleIconName", "appicon")}
${pair("CFBundleIdentifier", product.identifier)}
${pair("CFBundleName", product.name)}
${pair("CFBundlePackageType", "APPL")}
${pair("CFBundleShortVersionString", product.version)}
${pair("CFBundleVersion", product.version)}
${development ? "    <key>NSAppTransportSecurity</key>\n    <dict>\n      <key>NSAllowsLocalNetworking</key>\n      <true/>\n    </dict>\n" : ""}    <key>NSHighResolutionCapable</key>
    <true/>
${pair("NSHumanReadableCopyright", product.copyright)}
  </dict>
</plist>
`;
}

function appearanceBootstrap(facts) {
  return `// ${generated}
(function () {
  const systemDark = !!window.matchMedia && window.matchMedia("(prefers-color-scheme: dark)").matches;
  let scheme = systemDark ? "dark" : "light";
  let state;
  let paint;
  try {
    const raw = localStorage.getItem(${JSON.stringify(facts.storage.appearance)});
    state = raw ? JSON.parse(raw)?.state : undefined;
    const id = state?.theme;
    if (id === "light" || id === "dark") scheme = id;
    else if (id && id !== "system") {
      const rawPaint = localStorage.getItem(${JSON.stringify(facts.storage.paint)});
      const candidate = rawPaint ? JSON.parse(rawPaint) : undefined;
      if (candidate?.theme === id && (candidate.scheme === "light" || candidate.scheme === "dark") && /^#[0-9a-fA-F]{6}$/.test(candidate.background)) {
        paint = candidate;
        scheme = paint.scheme;
      }
    }
  } catch (_) {}
  const documentRoot = document.documentElement;
  documentRoot.dataset.visualStyle = typeof state?.visualStyle === "string" && state.visualStyle ? state.visualStyle : ${JSON.stringify(facts.preference.visualStyle)};
  documentRoot.classList.add(${JSON.stringify(facts.themeClassPrefix)} + scheme);
  documentRoot.style.backgroundColor = paint?.background ?? (scheme === "light" ? ${JSON.stringify(facts.light["color-bg"])} : ${JSON.stringify(facts.dark["color-bg"])});
})();
`;
}

function stylesheet(facts) {
  const declarations = (values) =>
    Object.entries(values)
      .map(([key, value]) => `  --${key}: ${value};`)
      .join("\n");
  return `/* ${generated} */\n:root {\n${declarations({ ...facts.light, ...facts.defaults })}\n}\n\nhtml.${facts.themeClassPrefix}dark {\n${declarations(facts.dark)}\n}\n`;
}

function nativeSource(facts) {
  const rgb = (hex) => {
    if (!/^#[\da-f]{6}$/i.test(hex))
      throw new Error("native canvas requires an opaque RGB color");
    return [1, 3, 5].map((offset) =>
      Number.parseInt(hex.slice(offset, offset + 2), 16),
    );
  };
  const [lightRed, lightGreen, lightBlue] = rgb(facts.light["color-bg"]);
  const [darkRed, darkGreen, darkBlue] = rgb(facts.dark["color-bg"]);
  return execFileSync("gofmt", [], {
    encoding: "utf8",
    input: `// Code generated by tooling/presentation.mjs. DO NOT EDIT.\npackage main\n\nconst (\n\tproductName = ${JSON.stringify(facts.product.name)}\n\tproductDescription = ${JSON.stringify(facts.product.description)}\n\tbootstrapLightRed = ${lightRed}\n\tbootstrapLightGreen = ${lightGreen}\n\tbootstrapLightBlue = ${lightBlue}\n\tbootstrapDarkRed = ${darkRed}\n\tbootstrapDarkGreen = ${darkGreen}\n\tbootstrapDarkBlue = ${darkBlue}\n)\n`,
  });
}

export async function presentationOutputs(repository = root) {
  const facts = await presentationFacts(repository);
  const template = await readFile(
    join(repository, "apps/web/index.template.html"),
    "utf8",
  );
  if (template.split("{{PRODUCT_NAME}}").length !== 2)
    throw new Error("Web entry template requires one product name projection");
  const html = template
    .replace("{{PRODUCT_NAME}}", escapeXML(facts.product.name))
    .replace("<!doctype html>", `<!doctype html>\n<!-- ${generated} -->`);
  const formatted = async (path, content, parser) =>
    format(content, {
      ...(await resolveConfig(join(repository, path))),
      parser,
    });
  const outputs = new Map([
    [
      "apps/web/index.html",
      await formatted("apps/web/index.html", html, "html"),
    ],
    [
      "apps/web/public/appearance.generated.js",
      await formatted(
        "apps/web/public/appearance.generated.js",
        appearanceBootstrap(facts),
        "babel",
      ),
    ],
    [
      "apps/web/src/styles/presentation.generated.css",
      await formatted(
        "apps/web/src/styles/presentation.generated.css",
        stylesheet(facts),
        "css",
      ),
    ],
    ["apps/desktop/product.generated.go", nativeSource(facts)],
    [
      "apps/desktop/build/product.generated.json",
      await formatted(
        "apps/desktop/build/product.generated.json",
        JSON.stringify(facts.product),
        "json",
      ),
    ],
    ["apps/desktop/build/darwin/Info.plist", nativePlist(facts.product, false)],
    [
      "apps/desktop/build/darwin/Info.dev.plist",
      nativePlist(facts.product, true),
    ],
  ]);
  return outputs;
}

export async function generatePresentation(repository = root) {
  for (const [path, content] of await presentationOutputs(repository)) {
    await mkdir(dirname(join(repository, path)), { recursive: true });
    await writeFile(join(repository, path), content);
  }
}

export async function checkPresentation(repository = root) {
  const mismatches = [];
  for (const [path, content] of await presentationOutputs(repository)) {
    let current;
    try {
      current = await readFile(join(repository, path), "utf8");
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    if (current !== content) mismatches.push(path);
  }
  if (mismatches.length)
    throw new Error(
      `presentation projections differ: ${mismatches.join(", ")}`,
    );
}
