package main

import (
	"flag"
	"fmt"
	"go/ast"
	"go/constant"
	"go/format"
	"go/token"
	"go/types"
	"iter"
	"maps"
	"os"
	"slices"
	"strings"

	"github.com/Tangerg/flame/packages/go-sdk/filesystem"
	"golang.org/x/tools/go/packages"
)

func main() {
	source := flag.String("source", "", "directory of the package that declares the wire enums")
	out := flag.String("out", "", "generated Go file")
	flag.Parse()
	if *source == "" || *out == "" || flag.NArg() != 0 {
		fmt.Fprintln(os.Stderr, "wireenum: source and out are required")
		os.Exit(1)
	}
	if err := generate(*source, *out); err != nil {
		fmt.Fprintln(os.Stderr, "wireenum:", err)
		os.Exit(1)
	}
}

func generate(source, out string) error {
	config := &packages.Config{
		Dir:  source,
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax | packages.NeedTypes | packages.NeedTypesInfo,
	}
	loaded, err := packages.Load(config, ".")
	if err != nil {
		return fmt.Errorf("load enum declarations: %w", err)
	}
	if len(loaded) != 1 {
		return fmt.Errorf("load enum declarations: expected one package, got %d", len(loaded))
	}
	pkg := loaded[0]
	if len(pkg.Errors) != 0 {
		return fmt.Errorf("load enum declarations: %v", pkg.Errors)
	}
	vocabulary, err := closedEnums(pkg)
	if err != nil {
		return err
	}
	var code strings.Builder
	fmt.Fprintf(&code, "// Code generated by wireenum. DO NOT EDIT.\n\npackage %s\n", pkg.Name)
	for _, typeName := range slices.Sorted(maps.Keys(vocabulary)) {
		fmt.Fprintf(&code, "\nfunc (%s) wireEnumValues() []string {\n\treturn []string{\n", typeName)
		for _, member := range vocabulary[typeName] {
			fmt.Fprintf(&code, "\t\tstring(%s),\n", member.name)
		}
		code.WriteString("\t}\n}\n")
	}
	generated, err := format.Source([]byte(code.String()))
	if err != nil {
		return fmt.Errorf("format Go vocabulary: %w", err)
	}
	return os.WriteFile(out, generated, filesystem.SharedFileMode)
}

type enumMember struct {
	name  string
	value string
}

func markEnums(pkg *packages.Package, group *ast.GenDecl, marked map[string]bool) error {
	if enumMarker(group.Doc) && len(group.Specs) != 1 {
		return fmt.Errorf("enum marker requires one named type")
	}
	for _, item := range group.Specs {
		spec, ok := item.(*ast.TypeSpec)
		if !ok || (!enumMarker(spec.Doc) && !enumMarker(group.Doc)) {
			continue
		}
		object, ok := pkg.TypesInfo.Defs[spec.Name].(*types.TypeName)
		if !ok || object.IsAlias() {
			return fmt.Errorf("enum %s must be a named string type", spec.Name.Name)
		}
		basic, ok := object.Type().Underlying().(*types.Basic)
		if !ok || basic.Kind() != types.String {
			return fmt.Errorf("enum %s must have string underlying type", object.Name())
		}
		marked[object.Name()] = true
	}
	return nil
}

func closedEnums(pkg *packages.Package) (map[string][]enumMember, error) {
	marked := map[string]bool{}
	for _, file := range pkg.Syntax {
		for _, declaration := range file.Decls {
			group, ok := declaration.(*ast.GenDecl)
			if !ok || group.Tok != token.TYPE {
				continue
			}
			if err := markEnums(pkg, group, marked); err != nil {
				return nil, err
			}
		}
	}
	values := enumConstants(pkg, marked)
	for name := range marked {
		if len(values[name]) == 0 {
			return nil, fmt.Errorf("enum %s has no typed constants", name)
		}
	}
	return values, nil
}

func enumMarker(group *ast.CommentGroup) bool {
	if group == nil {
		return false
	}
	for _, comment := range group.List {
		if strings.TrimSpace(comment.Text) == "//flame:enum" {
			return true
		}
	}
	return false
}

func enumConstants(pkg *packages.Package, marked map[string]bool) map[string][]enumMember {
	files := slices.Clone(pkg.Syntax)
	slices.SortFunc(files, func(a, b *ast.File) int {
		return strings.Compare(pkg.Fset.Position(a.Pos()).Filename, pkg.Fset.Position(b.Pos()).Filename)
	})
	values := make(map[string][]enumMember, len(marked))
	for _, file := range files {
		for name := range constantNames(file) {
			key, text, ok := localStringConstant(pkg, name)
			if ok && marked[key] && !slices.ContainsFunc(values[key], func(member enumMember) bool {
				return member.value == text
			}) {
				values[key] = append(values[key], enumMember{name: name.Name, value: text})
			}
		}
	}
	return values
}

func constantNames(file *ast.File) iter.Seq[*ast.Ident] {
	return func(yield func(*ast.Ident) bool) {
		for _, declaration := range file.Decls {
			group, ok := declaration.(*ast.GenDecl)
			if !ok || group.Tok != token.CONST {
				continue
			}
			for _, item := range group.Specs {
				spec, ok := item.(*ast.ValueSpec)
				if !ok {
					continue
				}
				for _, name := range spec.Names {
					if !yield(name) {
						return
					}
				}
			}
		}
	}
}

func localStringConstant(pkg *packages.Package, name *ast.Ident) (string, string, bool) {
	value, ok := pkg.TypesInfo.Defs[name].(*types.Const)
	if !ok || value.Val().Kind() != constant.String {
		return "", "", false
	}
	named, ok := types.Unalias(value.Type()).(*types.Named)
	if !ok || named.Obj().Pkg() != pkg.Types {
		return "", "", false
	}
	return named.Obj().Name(), constant.StringVal(value.Val()), true
}
